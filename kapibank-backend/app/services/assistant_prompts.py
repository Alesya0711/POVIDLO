def allowed_targets(context):
    """Match the forms that actually implement onApply, never just the field name."""
    screen, field = context.get("screen"), context.get("field")
    if screen == "product" and field == "financing_terms":
        return ("principal", "termMonths")
    if screen == "questionnaire":
        if field in ("principal", "termMonths"):
            return (field,)
        data = context.get("data")
        answers = data.get("answers") if isinstance(data, dict) else None
        if field == "industryDescription" and isinstance(answers, dict) and answers.get("industry") == "other":
            return ("industryDescription",)
    return ()


def system_prompt(context):
    import json

    targets = allowed_targets(context)
    screen = context.get("screen")
    scenario = SCREEN_PROMPTS.get(screen if isinstance(screen, str) else None,
                                  "Объясняй только предоставленные данные. На этом экране правки недоступны.")
    examples = EXAMPLES.get(targets[0], []) if len(targets) == 1 else []
    if not examples:
        examples = [{"question": "Что такое monthlyPayment?", "answer": {
            "reply": "Это ежемесячный платёж: сумма, которую возвращают каждый месяц. Точное значение можно посмотреть в расчёте выбранного продукта.",
            "proposal": None}}]
    return (SYSTEM_PROMPT + "\n" + INTERFACE_PROMPT + "\nТекущий сценарий: " + scenario
            + "\nПримеры подходящего тона и формата (не факты текущего диалога): "
            + json.dumps(examples, ensure_ascii=False)
            + "\nРазрешённые поля proposal: " + (", ".join(targets) if targets else "нет, только null")
            + ". Версия инструкций: " + PROMPT_VERSION
            + "\nПеред ответом проверь: текст для человека по-русски; названия кнопок совпадают с интерфейсом; "
              "нет служебных кодов, выдуманных условий и заявлений о выполненном действии. "
              "Сама проверка в ответ не входит.")


def response_format(context):
    variants = [{"type": "null"}]
    for target in allowed_targets(context):
        variants.append({
            "type": "object",
            "properties": {
                "targetField": {"type": "string", "enum": [target]},
                "proposedValue": {"type": "integer" if target == "termMonths" else "string"},
                "explanation": {"type": "string"},
            },
            "required": ["targetField", "proposedValue", "explanation"],
            "additionalProperties": False,
        })
    return {"type": "json_schema", "json_schema": {
        "name": "kapibank_assistant", "strict": True,
        "schema": {
            "type": "object",
            "properties": {"reply": {"type": "string"}, "proposal": {"anyOf": variants}},
            "required": ["reply", "proposal"], "additionalProperties": False,
        },
    }}
