REPORT_PERIODS = [
    "2026-04",
    "2026-05",
    "2026-06",
    "2026-07",
    "2026-08",
    "2026-09",
]


def _build_monthly_reports(prev_rev: str, curr_rev: str, opex: str) -> list[dict]:
    """Генерирует 6 полных отчётных месяцев, где среднее за 1..3 мес = prev_rev, за 4..6 мес = curr_rev."""
    return [
        {"period": REPORT_PERIODS[0], "revenue": prev_rev, "operatingExpenses": opex},
        {"period": REPORT_PERIODS[1], "revenue": prev_rev, "operatingExpenses": opex},
        {"period": REPORT_PERIODS[2], "revenue": prev_rev, "operatingExpenses": opex},
        {"period": REPORT_PERIODS[3], "revenue": curr_rev, "operatingExpenses": opex},
        {"period": REPORT_PERIODS[4], "revenue": curr_rev, "operatingExpenses": opex},
        {"period": REPORT_PERIODS[5], "revenue": curr_rev, "operatingExpenses": opex},
    ]


def _build_supporting_records(
    profile_id: str,
    company_name: str,
    registry_status: str,
    revenue: str,
    opex: str,
    bki_status: str,
) -> list[dict]:
    return [
        {
            "id": f"doc-reg-{profile_id}",
            "type": "registry_extract",
            "title": "Сведения о регистрации компании",
            "period": "2026-10-01",
            "source": "mock_fns_registry",
            "verificationResult": "verified" if registry_status == "active" else "failed",
            "summary": f"Компания «{company_name}», регистрация: {'действует' if registry_status == 'active' else 'прекращена'}",
        },
        {
            "id": f"doc-fin-{profile_id}",
            "type": "financial_statement",
            "title": "Управленческая и налоговая отчётность за 6 месяцев",
            "period": "2026-04..2026-09",
            "source": "mock_accounting_source",
            "verificationResult": "verified",
            "summary": f"Средняя выручка (3 мес.): {revenue} ₽, операционные расходы: {opex} ₽",
        },
        {
            "id": f"doc-bki-{profile_id}",
            "type": "credit_bureau_report",
            "title": "Сведения о кредитной истории",
            "period": "2026-10-01",
            "source": "mock_bki",
            "verificationResult": "unavailable" if bki_status == "source_unavailable" else "verified",
            "summary": "Кредитная история: " + {"ok": "есть сведения", "empty": "кредитов не было", "source_unavailable": "сведения недоступны"}.get(bki_status, "нет данных"),
        },
    ]


